# 定义每个数据集的总计数（用于转换为百分比）
# 如果某个数据集没有定义总计数，则保持原始数值
total_counts = {
    "ehsm": 0xE3F1,
    "intel-sgx-ssl": 0xD510,
    "SGX-SQLite": 0x4B30,
    "sgx-reencrypt": 0x81D,
    "sgx-wallet": 0x6A4,
    "SGXCryptoFile": 0x549,
    "wasm-micro-runtime": 0x4089,
}

# 准备所有数据（包含原始数据和新数据）
datasets = [
    ("ehsm", ehsm_data, ehsm_data_orig),
    ("intel-sgx-ssl", intel_sgx_ssl_data, intel_sgx_ssl_data_orig),
    ("SGX-SQLite", SGX_SQLite_data, SGX_SQLite_data_orig),
    ("sgx-reencrypt", sgx_reencrypt_data, sgx_reencrypt_data_orig),
    ("sgx-wallet", sgx_wallet_data, sgx_wallet_data_orig),
    # ("SGXCryptoFile", SGXCryptoFile_data, SGXCryptoFile_data_orig),
    ("wasm-micro-runtime", wasm_micro_runtime_data, wasm_micro_runtime_data_orig),
]

# 定义颜色
colors = ["#2E86AB", "#A23B72", "#F18F01", "#C73E1D", "#6A994E", "#BC4B51", "#8B5A3C"]

# 打印最终覆盖率百分比
print("Final Coverage:")
for name, data, data_orig in datasets:
    total_count = total_counts.get(name)
    if data and total_count:
        final_coverage = data[-1][0]
        final_percent = (final_coverage / total_count) * 100
        print(f"{name} (patched): {final_percent:.2f}%")
    if data_orig and total_count:
        final_coverage_orig = data_orig[-1][0]
        print(f"{name} (no_patch): {final_coverage_orig:.2f}%")

# 创建图表，7个子图排列成 3行3列（最后一行中间有一个空位）
fig, axes = plt.subplots(2, 3, figsize=(18, 8))
axes = axes.flatten()  # 将2D数组展平为1D，方便索引

# 为每组数据绘制到单独的子图（每个子图包含data和data_orig的对比）
for i, (name, data, data_orig) in enumerate(datasets):
    # 检查是否需要转换为百分比
    total_count = total_counts.get(name)

    # 绘制新数据
    time_data = [x[1] for x in data]
    if total_count:
        coverage_data = [(x[0] / total_count) * 100 for x in data]
    else:
        coverage_data = [x[0] for x in data]
    axes[i].plot(
        time_data, coverage_data, linewidth=2, color=colors[i], label="patched"
    )

    # 绘制原始数据
    time_data_orig = [x[1] for x in data_orig]
    coverage_data_orig = [x[0] for x in data_orig]
    axes[i].plot(
        time_data_orig,
        coverage_data_orig,
        linewidth=2,
        color=colors[i],
        linestyle="--",
        alpha=0.7,
        label="no_patch",
    )

    axes[i].set_xlabel("Time (seconds)", fontsize=10)
    # 根据是否转换百分比设置Y轴标签
    if total_count:
        axes[i].set_ylabel("Coverage (%)", fontsize=10)
    else:
        axes[i].set_ylabel("Coverage", fontsize=10)
    axes[i].set_title(name, fontsize=12, fontweight="bold")
    axes[i].grid(True, alpha=0.3, linestyle="--")
    axes[i].legend(loc="best", fontsize=8)

